export function t(key: Key, params: Record<string, string | number> = {}): string {
  const s = dicts[store.data.settings.lang]?.[key] ?? it[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, p) => String(params[p] ?? `{${p}}`));
}

